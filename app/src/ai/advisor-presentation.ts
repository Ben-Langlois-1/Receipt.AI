import { desktopBridge } from './desktop-bridge.ts'
import { useState } from 'react'
import { createElement as h, type ReactNode } from 'react'
import type { AdvisorReport } from './advisor-report.ts'
import { formatCents } from './financial-facts.ts'

// Deliberately small Markdown subset: text nodes only, no raw HTML, links or images.
function inline(text: string): ReactNode[] {
  return text.split(/(\*\*[^*]+\*\*|\*[^*]+\*|`[^`]+`)/g).map((part, index) => {
    if (part.startsWith('**') && part.endsWith('**')) return h('strong', { key: index }, part.slice(2, -2))
    if (part.startsWith('*') && part.endsWith('*')) return h('em', { key: index }, part.slice(1, -1))
    if (part.startsWith('`') && part.endsWith('`')) return h('code', { key: index }, part.slice(1, -1))
    return part
  })
}
export function AdvisorMarkdown({ text }: { text: string }) {
  const blocks: ReactNode[] = []
  const lines = text.replace(/\r\n?/g, '\n').split('\n')
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    if (!line.trim()) continue
    const list = /^\s*(?:[-*+]\s+|\d+[.)]\s+)/.test(line)
    if (list) {
      const ordered = /^\s*\d+[.)]/.test(line)
      const items: ReactNode[] = []
      const pattern = ordered ? /^\s*\d+[.)]\s+/ : /^\s*[-*+]\s+/
      while (i < lines.length && pattern.test(lines[i])) {
        items.push(h('li', { key: i }, ...inline(lines[i].replace(pattern, ''))))
        i++
      }
      i--
      blocks.push(h(ordered ? 'ol' : 'ul', { key: i }, ...items))
    } else {
      const heading = /^(#{1,3})\s+(.+)$/.exec(line)
      blocks.push(h(heading ? 'h4' : 'p', { key: i }, ...inline(heading ? heading[2] : line)))
    }
  }
  return h('div', { className: 'advisor-markdown' }, ...blocks)
}
const amount = (value: number | null, currency: string) => value === null ? 'Unknown' : `${formatCents(value)} ${currency}`
const categoryLine = (c: { category: string; outflowCents: number; share?: string }, currency: string) => `${c.category}: ${amount(c.outflowCents, currency)}${c.share ? ` (${c.share} of outflows)` : ''}`
const comparisonLine = (c: AdvisorReport['comparisons'][number]) => `${c.category ? c.category + ': ' : ''}${c.currentMonth} versus ${c.previousMonth}: imported outflow difference ${amount(c.differenceCents, c.currency)}; change ${c.percentageChange === null ? 'unavailable (zero baseline)' : `${c.percentageChange}%`}`
const futureLine = (report: AdvisorReport) => report.futureDatedRecords ? `Future-dated records: ${report.futureDatedRecords.transactions} imported transaction${report.futureDatedRecords.transactions === 1 ? '' : 's'} dated ${report.futureDatedRecords.earliest} through ${report.futureDatedRecords.latest} occur after ${report.asOfDate}. They are included in these figures; verify their dates before acting on them.` : ''
export function answerSourceLabel(report: AdvisorReport): string {
  if (report.explanationStatus === 'checked') return 'AI-generated by the local model from the verified figures below and checked against them. Verify important figures.'
  if (report.explanationStatus === 'withheld') return 'Calculated by Receipt.AI. The local AI answer was withheld because it did not pass the verification checks.'
  if (report.explanationStatus === 'unavailable') return `Calculated by Receipt.AI. Local AI unavailable: ${report.unavailableReason ?? 'no answer was returned.'}`
  return 'Calculated by Receipt.AI.'
}
export function AdvisorResponse({ report }: { report: AdvisorReport }) {
  const hasDetails = report.figures.length > 0 || report.comparisons.length > 0
  return h('div', { className: 'advisor-report' },
    h('section', { 'aria-label': 'Answer' },
      h(AdvisorMarkdown, { text: report.answer }),
      h('p', { className: 'muted' }, answerSourceLabel(report))),
    report.futureDatedRecords ? h('p', { role: 'alert' }, futureLine(report)) : null,
    hasDetails ? h('details', null,
      h('summary', null, 'Verified financial figures and details'),
      h('section', { 'aria-label': 'Verified financial figures' },
        h('p', { className: 'muted' }, `Calculated from imported records · As of ${report.asOfDate} · ${report.timezone}`),
        ...report.figures.map((row, i) => h('div', { key: i, className: 'advisor-figures' },
          h('h4', null, `${row.period} · ${row.currency}`),
          h('p', null, row.endExclusive ? `${row.startInclusive} inclusive to ${row.endExclusive} exclusive` : `Imported date range: ${row.startInclusive} through ${row.endInclusive} inclusive`),
          h('p', null, row.coverage === 'no_records' ? 'Coverage: no records found; spending unknown.' : `Coverage: unverified · ${row.transactions} imported transactions`),
          h('dl', null,
            h('dt', null, 'Outflows'), h('dd', null, amount(row.outflowCents, row.currency)),
            h('dt', null, 'Inflows'), h('dd', null, amount(row.inflowCents, row.currency)),
            h('dt', null, 'Net cash flow'), h('dd', null, amount(row.netFlowCents, row.currency))),
          // Rendered whenever the figures are open; never hidden behind a second collapsed level.
          row.categories.length ? h('p', null, 'Category outflows (labels unverified)') : null,
          row.categories.length ? h('ul', null, ...row.categories.map((c, index) => h('li', { key: index }, categoryLine(c, row.currency)))) : null)),
        ...report.comparisons.map((c, i) => h('p', { key: `comparison-${i}` }, `${comparisonLine(c)}. Coverage is unverified; this is not a complete spending comparison.`)),
        h('p', null, report.notice),
        report.explanationAttempts?.some((a) => a.reasons.length) ? h('p', null, 'AI answer checks') : null,
        report.explanationAttempts?.some((a) => a.reasons.length) ? h('ul', null, ...report.explanationAttempts.map((attempt, index) => h('li', { key: index },
          `Attempt ${index + 1}: ${attempt.reasons.length ? attempt.reasons.join(', ') : 'accepted'}`))) : null)) : null,
    h(CopyAdvisorReport, { report }))
}

/** Serialize the data, not collapsed DOM details, for reliable clipboard output. */
export function reportToPlainText(report: AdvisorReport): string {
  const lines = ['Answer', report.answer, `(${answerSourceLabel(report)})`, '', 'Verified financial figures', `As of ${report.asOfDate} · ${report.timezone}`]
  if (report.futureDatedRecords) lines.push(futureLine(report))
  for (const row of report.figures) {
    lines.push(`${row.period} · ${row.currency}`, row.endExclusive ? `${row.startInclusive} inclusive to ${row.endExclusive} exclusive` : `${row.startInclusive} through ${row.endInclusive} inclusive`,
      `Coverage: ${row.coverage === 'no_records' ? 'no records; spending unknown' : 'unverified'} · ${row.transactions} imported transactions`,
      `Outflows: ${amount(row.outflowCents, row.currency)}`, `Inflows: ${amount(row.inflowCents, row.currency)}`, `Net cash flow: ${amount(row.netFlowCents, row.currency)}`)
    if (row.categories.length) lines.push('Category outflows (labels unverified):')
    for (const category of row.categories) lines.push(`- ${categoryLine(category, row.currency)}`)
  }
  for (const c of report.comparisons) lines.push(`${comparisonLine(c)}. Coverage unverified.`)
  lines.push(report.notice)
  for (const [index, attempt] of (report.explanationAttempts ?? []).entries()) lines.push(`- AI answer attempt ${index + 1}: ${attempt.reasons.length ? attempt.reasons.join(', ') : 'accepted'}`)
  return lines.join('\n')
}
function CopyAdvisorReport({ report }: { report: AdvisorReport }) {
  const [status, setStatus] = useState('')
  return h('div', null,
    h('button', { type: 'button', onClick: async () => {
      try { if (desktopBridge()) await desktopBridge()!.copyText(reportToPlainText(report)); else await navigator.clipboard.writeText(reportToPlainText(report)); setStatus('Report copied.') }
      catch { setStatus('Unable to copy. Check browser clipboard permission.') }
    } }, 'Copy report'),
    h('span', { role: 'status', className: 'muted' }, status))
}
